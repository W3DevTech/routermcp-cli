/**
 * Write THIRD_PARTY_NOTICES.md for every package in the production dependency
 * tree. `bun run build` bundles these packages into dist/index.js and
 * minification strips their license headers, so the notices ship as a
 * separate file in the npm tarball instead.
 *
 * Usage: bun run scripts/generate-third-party-notices.ts [--check]
 *   --check  exit 1 if the committed file is out of date (used in CI)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const OUTPUT = join(ROOT, "THIRD_PARTY_NOTICES.md");
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

interface PackageJson {
  name: string;
  version: string;
  license?: string | { type?: string };
  licenses?: { type?: string }[];
  repository?: string | { url?: string };
  homepage?: string;
  dependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
  peerDependenciesMeta?: Record<string, { optional?: boolean }>;
}

interface Notice {
  name: string;
  version: string;
  license: string;
  source?: string;
  texts: { file: string; text: string }[];
}

function readPackage(dir: string): PackageJson {
  return JSON.parse(readFileSync(join(dir, "package.json"), "utf-8")) as PackageJson;
}

/** Resolve a dependency the way Node does: nearest node_modules walking up. */
function findPackageDir(name: string, fromDir: string): string | null {
  let dir = fromDir;
  while (true) {
    const candidate = join(dir, "node_modules", name);
    if (existsSync(join(candidate, "package.json"))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function licenseOf(pkg: PackageJson): string {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  const legacy = pkg.licenses?.map((entry) => entry.type).filter(Boolean);
  return legacy?.length ? legacy.join(" OR ") : "UNKNOWN";
}

function sourceOf(pkg: PackageJson): string | undefined {
  const repository = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  const url = repository ?? pkg.homepage;
  if (!url) return undefined;
  return url
    .replace(/^git\+/, "")
    .replace(/\.git$/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^github:/, "https://github.com/")
    .replace(/^([\w-]+\/[\w.-]+)$/, "https://github.com/$1");
}

function collectNotices(): Notice[] {
  const root = readPackage(ROOT);
  const notices = new Map<string, Notice>();
  const queue: { name: string; from: string }[] = Object.keys(root.dependencies ?? {}).map(
    (name) => ({ name, from: ROOT }),
  );

  while (queue.length > 0) {
    const { name, from } = queue.shift() as { name: string; from: string };
    const dir = findPackageDir(name, from);
    if (!dir) {
      // Optional and peer dependencies may legitimately be absent.
      continue;
    }
    const pkg = readPackage(dir);
    const key = `${pkg.name}@${pkg.version}`;
    if (notices.has(key)) continue;

    const texts = readdirSync(dir)
      .filter((file) => LICENSE_FILE.test(file))
      .sort()
      .map((file) => ({ file, text: readFileSync(join(dir, file), "utf-8").trim() }));
    notices.set(key, {
      name: pkg.name,
      version: pkg.version,
      license: licenseOf(pkg),
      source: sourceOf(pkg),
      texts,
    });

    // Optional peers are only present if something else installed them, so
    // following them would make the output depend on the local node_modules.
    const requiredPeers = Object.keys(pkg.peerDependencies ?? {}).filter(
      (peer) => !pkg.peerDependenciesMeta?.[peer]?.optional,
    );
    for (const dep of new Set([
      ...Object.keys(pkg.dependencies ?? {}),
      ...Object.keys(pkg.optionalDependencies ?? {}),
      ...requiredPeers,
    ])) {
      queue.push({ name: dep, from: dir });
    }
  }

  return [...notices.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
}

function render(notices: Notice[]): string {
  const lines = [
    "# Third-Party Notices",
    "",
    "RouterMCP bundles the following open source packages into `dist/index.js`.",
    "Their license notices are reproduced below as their licenses require.",
    "",
    "This file is generated by `bun run notices`; do not edit it by hand.",
    "",
    "| Package | Version | License |",
    "| --- | --- | --- |",
    ...notices.map((n) => `| ${n.name} | ${n.version} | ${n.license} |`),
    "",
  ];

  for (const notice of notices) {
    lines.push("---", "", `## ${notice.name}@${notice.version}`, "");
    lines.push(`License: ${notice.license}`);
    if (notice.source) lines.push(`Source: ${notice.source}`);
    lines.push("");
    if (notice.texts.length === 0) {
      lines.push(
        `No license file is included in the published package; see the ${notice.license} license terms.`,
        "",
      );
    }
    for (const { file, text } of notice.texts) {
      lines.push(`### ${file}`, "", "```text", text, "```", "");
    }
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

const output = render(collectNotices());

if (process.argv.includes("--check")) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf-8") : "";
  if (current !== output) {
    console.error("THIRD_PARTY_NOTICES.md is out of date. Run `bun run notices` and commit it.");
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is up to date.");
} else {
  writeFileSync(OUTPUT, output, "utf-8");
  console.log(`Wrote ${OUTPUT}`);
}

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync, spawnSync } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "vitest";
import {
  SEARCH_CONTRACT_SOURCE_FILES,
  targetPathForSource,
} from "../../scripts/search-contract-files.mjs";
import {
  SEARCH_CONTRACT_SOURCE_PACKAGE,
  SEARCH_CONTRACT_SOURCE_REPOSITORY,
} from "../../scripts/search-contract-source.mjs";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

function git(repository: string, ...args: string[]) {
  return execFileSync("git", ["-C", repository, ...args], { encoding: "utf8" }).trim();
}

function digest(bytes: Buffer) {
  return createHash("sha256").update(bytes).digest("hex");
}

function shellQuote(value: string) {
  return `'${value.replaceAll("'", "'\"'\"'")}'`;
}

function runVerifier(verifierRoot: string, args: string[] = [], env: NodeJS.ProcessEnv = {}) {
  return spawnSync(
    process.execPath,
    [path.join(verifierRoot, "scripts/verify-search-contract.mjs"), ...args],
    { cwd: verifierRoot, encoding: "utf8", env: { ...process.env, ...env } },
  );
}

test("the verifier binds generated bytes to the immutable pinned search source", async () => {
  const temporaryRoot = await mkdtemp(path.join(os.tmpdir(), "search-contract-verifier-"));
  const verifierRoot = path.join(temporaryRoot, "cli");
  const remote = path.join(temporaryRoot, "origin.git");
  const sourceRepository = path.join(temporaryRoot, "source");

  try {
    await mkdir(path.join(verifierRoot, "scripts"), { recursive: true });
    for (const script of [
      "verify-search-contract.mjs",
      "search-contract-files.mjs",
      "search-contract-source.mjs",
    ]) {
      await cp(
        path.join(repositoryRoot, "scripts", script),
        path.join(verifierRoot, "scripts", script),
      );
    }

    const sourceFiles = [];
    for (const sourceFile of SEARCH_CONTRACT_SOURCE_FILES) {
      const targetPath = targetPathForSource(sourceFile);
      const generatedBytes = await readFile(path.join(repositoryRoot, targetPath));
      const headerEnd = generatedBytes.indexOf(0x0a);
      assert.notEqual(headerEnd, -1, `Expected a generated header in ${targetPath}`);
      const sourceBytes = sourceFile.endsWith(".ts")
        ? generatedBytes.subarray(headerEnd + 1)
        : generatedBytes;
      sourceFiles.push({
        sourcePath: path.posix.join(SEARCH_CONTRACT_SOURCE_PACKAGE, sourceFile),
        sourceFile,
        targetPath,
        sourceBytes,
      });
    }

    git(temporaryRoot, "init", "--bare", "--initial-branch=main", remote);
    await mkdir(sourceRepository, { recursive: true });
    git(sourceRepository, "init", "--initial-branch=main");
    git(sourceRepository, "config", "user.name", "Search contract test");
    git(sourceRepository, "config", "user.email", "search-contract@example.test");
    git(sourceRepository, "remote", "add", "origin", SEARCH_CONTRACT_SOURCE_REPOSITORY);
    git(
      sourceRepository,
      "config",
      "remote.origin.pushurl",
      remote,
    );

    for (const file of sourceFiles) {
      const sourcePath = path.join(sourceRepository, file.sourcePath);
      await mkdir(path.dirname(sourcePath), { recursive: true });
      await writeFile(sourcePath, file.sourceBytes);
    }
    git(sourceRepository, "add", SEARCH_CONTRACT_SOURCE_PACKAGE);
    git(sourceRepository, "commit", "-m", "pin search contract fixture");
    const sourceCommit = git(sourceRepository, "rev-parse", "HEAD");
    git(sourceRepository, "push", "origin", "HEAD:refs/heads/main");

    const gitShimDirectory = path.join(temporaryRoot, "git-bin");
    await mkdir(gitShimDirectory);
    const gitPath = execFileSync("which", ["git"], { encoding: "utf8" }).trim();
    const gitShim = path.join(gitShimDirectory, "git");
    const quotedRemote = shellQuote(remote);
    const quotedGitPath = shellQuote(gitPath);
    await writeFile(
      gitShim,
      `#!/bin/sh
if [ "$1" = "-C" ] && [ "$3" = "fetch" ] && [ "$5" = "origin" ]; then
  set -- "$1" "$2" "$3" "$4" ${quotedRemote} "$6"
fi
exec ${quotedGitPath} "$@"
`,
      { mode: 0o755 },
    );
    const verifierEnv = { PATH: `${gitShimDirectory}${path.delimiter}${process.env.PATH ?? ""}` };

    const manifestFiles = [];
    for (const file of sourceFiles) {
      const generatedHeader = file.sourceFile.endsWith(".ts")
        ? Buffer.from(
            `// Generated from ${SEARCH_CONTRACT_SOURCE_REPOSITORY}@${sourceCommit}:` +
              `${file.sourcePath}. Do not edit.\n`,
          )
        : Buffer.alloc(0);
      const generatedBytes = Buffer.concat([generatedHeader, file.sourceBytes]);
      const target = path.join(verifierRoot, file.targetPath);
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, generatedBytes);
      manifestFiles.push({
        sourcePath: file.sourcePath,
        targetPath: file.targetPath,
        sourceSha256: digest(file.sourceBytes),
        sha256: digest(generatedBytes),
      });
    }

    const manifest = {
      manifestVersion: 2,
      sourceRepository: SEARCH_CONTRACT_SOURCE_REPOSITORY,
      sourceCommit,
      sourcePackage: SEARCH_CONTRACT_SOURCE_PACKAGE,
      contractVersion: 1,
      sourceState: "merged-provenance-verified",
      publishedRef: "refs/heads/main",
      publishedHead: sourceCommit,
      mergedParent: sourceCommit,
      files: manifestFiles.sort((left, right) => left.targetPath.localeCompare(right.targetPath)),
    };
    const manifestPath = path.join(verifierRoot, "src/core/search/source-manifest.json");
    await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

    const landingArgs = ["--source-repo", sourceRepository, "--merged-parent", sourceCommit];
    assert.equal(runVerifier(verifierRoot, [], verifierEnv).status, 0);
    const validLanding = runVerifier(verifierRoot, landingArgs, verifierEnv);
    assert.equal(validLanding.status, 0, validLanding.stderr);

    const tamperedEntry = manifest.files.find((file) => file.sourcePath.endsWith("/parser.ts"));
    assert.ok(tamperedEntry);
    const generatedPath = path.join(verifierRoot, tamperedEntry.targetPath);
    const generatedBytes = await readFile(generatedPath);
    const headerEnd = generatedBytes.indexOf(0x0a);
    assert.notEqual(headerEnd, -1);
    const changedSourceBytes = Buffer.concat([
      generatedBytes.subarray(headerEnd + 1),
      Buffer.from("\n// altered generated source\n"),
    ]);
    const changedGeneratedBytes = Buffer.concat([
      generatedBytes.subarray(0, headerEnd + 1),
      changedSourceBytes,
    ]);
    await writeFile(generatedPath, changedGeneratedBytes);
    tamperedEntry.sha256 = digest(changedGeneratedBytes);
    await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

    const staleSourceHash = runVerifier(verifierRoot, [], verifierEnv);
    assert.equal(staleSourceHash.status, 1);
    assert.match(staleSourceHash.stderr, /Generated search source digest mismatch/u);

    tamperedEntry.sourceSha256 = digest(changedSourceBytes);
    await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
    assert.equal(runVerifier(verifierRoot, [], verifierEnv).status, 0);

    const pinnedSourceMismatch = runVerifier(verifierRoot, landingArgs, verifierEnv);
    assert.equal(pinnedSourceMismatch.status, 1);
    assert.match(
      pinnedSourceMismatch.stderr,
      /Pinned search source digest mismatch: packages\/search\/src\/parser\.ts/u,
    );
  } finally {
    await rm(temporaryRoot, { recursive: true, force: true });
  }
});
